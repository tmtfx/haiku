from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List


MAX_FRAMES = 16
TRIGGER_MAP = {"immediate": 0, "on_idle": 1}


@dataclass
class Manifest:
    frame_count: int
    start_delay_ms: int
    idle_delay_ms: int
    speed: float
    trigger: int


@dataclass
class CursorAnimation:
    asset_name: str
    manifest: Manifest
    frames: List[bytes]


def _parse_manifest(path: Path) -> Manifest:
    fields: Dict[str, str] = {}
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.split("#", 1)[0].strip()
        if not line:
            continue
        if "=" not in line:
            raise ValueError(f"{path}: malformed line '{raw_line}'")
        key, value = line.split("=", 1)
        fields[key.strip()] = value.strip()

    required = ["frame_count", "start_delay_ms", "idle_delay_ms", "speed", "trigger"]
    missing = [name for name in required if name not in fields]
    if missing:
        raise ValueError(f"{path}: missing keys: {', '.join(missing)}")

    frame_count = int(fields["frame_count"], 10)
    start_delay_ms = int(fields["start_delay_ms"], 10)
    idle_delay_ms = int(fields["idle_delay_ms"], 10)
    speed = float(fields["speed"])
    trigger_raw = fields["trigger"]
    if trigger_raw in TRIGGER_MAP:
        trigger = TRIGGER_MAP[trigger_raw]
    else:
        trigger = int(trigger_raw, 10)

    if frame_count < 2 or frame_count > MAX_FRAMES:
        raise ValueError(f"{path}: frame_count must be in [2, {MAX_FRAMES}]")
    if start_delay_ms < 0 or idle_delay_ms < 0:
        raise ValueError(f"{path}: delays must be >= 0")
    if speed <= 0:
        raise ValueError(f"{path}: speed must be > 0")
    if trigger not in (0, 1):
        raise ValueError(f"{path}: trigger must be immediate/on_idle/0/1")

    return Manifest(
        frame_count=frame_count,
        start_delay_ms=start_delay_ms,
        idle_delay_ms=idle_delay_ms,
        speed=speed,
        trigger=trigger,
    )


def _load_frame_bytes(frames_dir: Path, index: int) -> bytes:
    base = f"frame_{index:02d}"
    for candidate in (frames_dir / base, frames_dir / f"{base}.hvif"):
        if candidate.exists():
            return candidate.read_bytes()
    raise FileNotFoundError(f"{frames_dir}: missing frame file {base}[.hvif]")


def _discover(root: Path) -> List[CursorAnimation]:
    result: List[CursorAnimation] = []
    for frames_dir in sorted(root.glob("*.frames")):
        if not frames_dir.is_dir():
            continue
        asset_name = frames_dir.name[: -len(".frames")]
        manifest_path = frames_dir / "animation.txt"
        if not manifest_path.exists():
            continue

        manifest = _parse_manifest(manifest_path)
        frames = [_load_frame_bytes(frames_dir, i) for i in range(1, manifest.frame_count)]
        result.append(CursorAnimation(asset_name=asset_name, manifest=manifest, frames=frames))
    return result


def _bytes_literal(data: bytes) -> str:
    columns = 16
    rows = []
    for i in range(0, len(data), columns):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i : i + columns])
        rows.append(f"\t{chunk},")
    if not rows:
        rows.append("\t")
    return "\n".join(rows)


def _emit(animations: List[CursorAnimation], output: Path) -> None:
    lines: List[str] = []
    lines.append("/*")
    lines.append(" * Auto-generated by generate_cursor_animation_data.py")
    lines.append(" * DO NOT EDIT MANUALLY.")
    lines.append(" */")
    lines.append("")
    lines.append('#include "CursorAnimationData.h"')
    lines.append("")
    lines.append("#include <string.h>")
    lines.append("")

    for animation in animations:
        for i, frame in enumerate(animation.frames, start=1):
            symbol = f"k{animation.asset_name}Frame{i:02d}"
            lines.append(f"static const uint8 {symbol}[] = {{")
            lines.append(_bytes_literal(frame))
            lines.append("};")
            lines.append("")

        frames_symbol = f"k{animation.asset_name}Frames"
        lines.append(f"static const cursor_animation_frame_data {frames_symbol}[] = {{")
        for i, frame in enumerate(animation.frames, start=1):
            symbol = f"k{animation.asset_name}Frame{i:02d}"
            lines.append(f"\t{{ {symbol}, sizeof({symbol}) }},")
        lines.append("};")
        lines.append("")

    lines.append("const cursor_animation_definition kSystemCursorAnimations[] = {")
    for animation in animations:
        frames_symbol = f"k{animation.asset_name}Frames"
        m = animation.manifest
        lines.append(
            "\t{ \"%s\", %d, %d, %d, %.6ff, %d, %s, %d },"
            % (
                animation.asset_name,
                m.frame_count,
                m.start_delay_ms,
                m.idle_delay_ms,
                m.speed,
                m.trigger,
                frames_symbol,
                len(animation.frames),
            )
        )
    lines.append("};")
    lines.append("")
    lines.append(
        "const size_t kSystemCursorAnimationCount"
        " = sizeof(kSystemCursorAnimations) / sizeof(kSystemCursorAnimations[0]);"
    )
    lines.append("")
    lines.append("const cursor_animation_definition*")
    lines.append("FindSystemCursorAnimationDefinition(const char* assetName)")
    lines.append("{")
    lines.append("\tif (assetName == NULL || assetName[0] == '\\0')")
    lines.append("\t\treturn NULL;")
    lines.append("")
    lines.append("\tfor (size_t i = 0; i < kSystemCursorAnimationCount; i++) {")
    lines.append("\t\tif (strcmp(kSystemCursorAnimations[i].assetName, assetName) == 0)")
    lines.append("\t\t\treturn &kSystemCursorAnimations[i];")
    lines.append("\t}")
    lines.append("")
    lines.append("\treturn NULL;")
    lines.append("}")
    lines.append("")

    output.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    animations = _discover(args.root)
    _emit(animations, args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
